def test_serialize_roundtrip():
    t = Task(
        title="Test",
        description="A test task",
        priority=TaskPriority.HIGH,
        dependencies=["dep1"],
        required_capabilities=["code.generate"],
        assigned_agent="agent1",
        estimated_duration=10.5,
        estimated_tokens=500,
        estimated_cost=0.01,
        metadata={"key": "value"},
    )
    t.mark_ready()
    t.mark_running()
    t.mark_completed()
    s = t.serialize()
    t2 = Task.deserialize(s)
    assert t2.id == t.id
    assert t2.title == t.title
    assert t2.description == t.description
    assert t2.priority == t.priority
    assert t2.status == t.status
    assert t2.dependencies == t.dependencies
    assert t2.required_capabilities == t.required_capabilities
    assert t2.assigned_agent == t.assigned_agent
    assert t2.estimated_duration == t.estimated_duration
    assert t2.estimated_tokens == t.estimated_tokens
    assert t2.estimated_cost == t.estimated_cost
    assert t2.metadata == t.metadata


