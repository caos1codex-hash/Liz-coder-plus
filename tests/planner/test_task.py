def test_task_post_init_copies_lists():
    deps = ["a", "b"]
    caps = ["x"]
    meta = {"k": "v"}
    t = Task(title="t", dependencies=deps, required_capabilities=caps, metadata=meta)
    deps.append("c")
    caps.append("y")
    meta["k"] = "changed"
    assert t.dependencies == ["a", "b"]
    assert t.required_capabilities == ["x"]
    assert t.metadata == {"k": "v"}


