def test_reset():
    t = Task(title="t")
    t.mark_ready()
    t.mark_running()
    t.mark_failed(error="x")
    t.assigned_agent = "agent1"
    t.reset()
    assert t.status == TaskStatus.PENDING
    assert t.assigned_agent is None
    assert t.retry_count == 0
    assert "last_error" not in t.metadata


